// MIGRATION_REPORT.md: every Clay column, what it became, what was left out
// and why, what to verify before deploying, and what a run costs.

import type { MigrationPlan, PlannedColumn } from "./plan.ts";

const KIND_LABEL: Record<string, string> = {
  input: "Input",
  "loader-formula": "Formula (inputs)",
  "body-formula": "Formula (results)",
  action: "Enrichment",
  ai: "AI column",
  "crm-write": "CRM write",
  source: "Source",
  "known-unverified": "Enrichment",
  unmapped: "Action",
};

function target(c: PlannedColumn): string {
  switch (c.kind) {
    case "input":
      return `model column \`${c.slug}\``;
    case "loader-formula":
      return `model column \`${c.slug}\`, computed at load`;
    case "body-formula":
      return `play writes \`${c.slug}\``;
    case "action":
      return `tool \`${c.slug}\` -> \`${c.mapping!.connector.integration}.${c.mapping!.action}\``;
    case "ai":
      return `agent + tool \`${c.slug}\``;
    default:
      return "not generated";
  }
}

function status(c: PlannedColumn): string {
  if (c.generated) return c.verify.length ? "migrated, verify" : "migrated";
  if (c.kind === "crm-write") return "left out on purpose";
  if (c.kind === "source") return "replaced by loader";
  return "needs manual review";
}

const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

export function buildReport(plan: MigrationPlan, opts: { rowCount?: number; schemaPath: string }): string {
  const cols = plan.columns;
  const migrated = cols.filter((c) => c.generated);
  const manual = cols.filter((c) => !c.generated && !["crm-write", "source"].includes(c.kind));
  const tools = migrated.filter((c) => c.kind === "action");
  const ai = migrated.filter((c) => c.kind === "ai");
  const conditional = migrated.filter((c) => c.conditionSource);
  const swaps = migrated.filter((c) => c.providerSwap);
  const verify = [...new Set(cols.flatMap((c) => c.verify))];
  const perRowMax = tools.reduce((s, c) => s + c.mapping!.credits, 0);
  const pilot = Math.min(opts.rowCount ?? 20, 20);

  const lines: string[] = [];
  lines.push(`# Migration report: Clay "${plan.name.replace(/_/g, " ")}" to Cargo`, "");
  lines.push(`Source: \`${opts.schemaPath}\` (ClayMate schema export). Generated by clay-to-cargo.`, "");
  lines.push(
    `**${migrated.length} of ${cols.length} columns migrated.** ` +
      `${tools.length} enrichment tool${tools.length === 1 ? "" : "s"}, ${ai.length} AI agent${ai.length === 1 ? "" : "s"}, ` +
      `${conditional.length} run condition${conditional.length === 1 ? "" : "s"} carried over, ${swaps.length} provider swap${swaps.length === 1 ? "" : "s"}. ` +
      `${manual.length} column${manual.length === 1 ? "" : "s"} need${manual.length === 1 ? "s" : ""} manual review.`,
    "",
  );

  lines.push("## Every column", "");
  lines.push("| # | Clay column | Clay type | Cargo | Status |", "|---|---|---|---|---|");
  for (const c of cols) {
    lines.push(`| ${c.clay.index} | ${cell(c.clay.name)} | ${KIND_LABEL[c.kind] ?? c.clay.type} | ${cell(target(c))} | ${status(c)} |`);
  }
  lines.push("");

  if (manual.length || cols.some((c) => c.kind === "crm-write" || c.kind === "source")) {
    lines.push("## Not migrated, and why", "");
    for (const c of cols.filter((x) => !x.generated)) {
      lines.push(`- **${c.clay.name}** (#${c.clay.index}): ${c.notes.join(" ")}`);
    }
    lines.push("");
  }

  if (conditional.length) {
    lines.push("## Run conditions and waterfalls", "");
    lines.push(
      "Each condition became a guard inside the column's tool. When it is false the tool returns nothing and makes no paid call. A waterfall needs no special handling: the later rung's condition reads the earlier rung's result.",
      "",
    );
    for (const c of conditional) lines.push(`- **${c.clay.name}**: runs only if \`${c.conditionSource}\``);
    lines.push("");
  }

  if (swaps.length) {
    lines.push("## Provider swaps", "");
    lines.push("Clay used providers Cargo does not run for these jobs. Each was swapped for the action Cargo's own clay-to-cargo recipe names. Fill rates can differ, which is what the parity check measures.", "");
    for (const c of swaps) lines.push(`- **${c.clay.name}**: \`${c.clay.typeSettings?.actionKey}\` -> \`${c.providerSwap!.to}\``);
    lines.push("");
  }

  const otherNotes = migrated.filter((c) => c.notes.some((n) => n.includes("dropped")));
  if (otherNotes.length) {
    lines.push("## Dropped inputs", "");
    for (const c of otherNotes) for (const n of c.notes.filter((x) => x.includes("dropped"))) lines.push(`- **${c.clay.name}**: ${n}`);
    lines.push("");
  }

  lines.push("## Cost", "");
  if (tools.length) {
    lines.push("| Column | Cargo action | Credits per call |", "|---|---|---|");
    for (const c of tools) lines.push(`| ${cell(c.clay.name)} | \`${c.mapping!.connector.integration}.${c.mapping!.action}\` | ${c.mapping!.credits} |`);
    lines.push("");
    lines.push(
      `Provider actions only: **${round(perRowMax)} credits per row** if every mapped enrichment runs. This excludes workflow execution and LLM costs. ` +
        `Provider subtotal for a ${pilot}-row pilot: **${round(perRowMax * pilot)} credits**` +
        (opts.rowCount ? `; provider subtotal for the full ${opts.rowCount}-row CSV: **${round(perRowMax * opts.rowCount)} credits**.` : "."),
    );
  }
  if (ai.length) lines.push("", "AI usage depends on the authenticated LLM connector and its billing configuration. Cargo may meter Anthropic usage; verify the destination connector and do not assume AI is outside Cargo credits. Workflow nodes also incur execution charges (the installed Cargo guidance states 0.01 credits per node execution). These are additional to the provider-action subtotal.");
  lines.push("", "Prices from Cargo's credits table (cargo-gtm/references/credits-cost-table.md). Do not compare them to Clay credits: different units. Compare what the same sample cost end to end on each side.", "");

  lines.push("## Verify before deploying", "");
  const checks = [
    "Run `npm run types` after `cargo-ai login`, then `npm run typecheck`. Connector actions are only typed against your workspace once types exist.",
    "Connect each integration in `connectors.ts` once in the Cargo app (they bind to the workspace default).",
    "Load 2 rows first and confirm in the app that values land in the model's columns.",
    ...verify,
  ];
  checks.forEach((v) => lines.push(`- [ ] ${v}`));
  lines.push("");

  lines.push("## Run it", "", "```bash");
  lines.push("cargo-ai project info  # declared resources");
  lines.push("cargo-ai project plan  # review the deployment diff");
  lines.push("cargo-ai project deploy  # only after reviewing and approving the plan");
  lines.push(`cargo-ai storage model list   # copy the uuid of ${plan.modelSlug}`);
  lines.push(`npx tsx scripts/clay-${plan.name.replace(/_/g, "-")}/load-rows.ts --csv <clay-export.csv> --model-uuid <uuid> --execute`);
  lines.push("# run the play once on the pilot rows from the app, then:");
  lines.push("npx tsx <path-to-clay-to-cargo>/src/cli.ts parity --schema <schema.json> --clay <clay-export.csv> --cargo <cargo-export.csv>");
  lines.push("```", "");
  lines.push("Enable the play only after the parity numbers are good enough for you. That call is yours, not the tool's.");

  return lines.join("\n") + "\n";
}

const round = (n: number) => Math.round(n * 100) / 100;
